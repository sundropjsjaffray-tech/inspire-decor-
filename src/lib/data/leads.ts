/** Compact timeline builder for seeded leads (created + last status change). */
const timeline = (
  statuses: Array<{ status: Lead["status"]; daysAgo: number; note?: string }>
): LeadTimelineEntry[] =>
  statuses.map((s) => ({
    status: s.status,
    at: new Date(Date.now() - s.daysAgo * 86_400_000).toISOString(),
    note: s.note,
  }));

